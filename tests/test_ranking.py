import pytest

from ranking import get_ranking, get_places


@pytest.mark.parametrize(
    "scores, expected",
    [
        # ① 全員の点数が異なる
        (
            {"東": 25000, "南": 35000, "西": 30000, "北": 10000},
            [
                ("南", 35000),
                ("西", 30000),
                ("東", 25000),
                ("北", 10000),
            ],
        ),
        # ② 同点のプレイヤーがいる
        (
            {"東": 30000, "南": 30000, "西": 25000, "北": 15000},
            [
                ("東", 30000),
                ("南", 30000),
                ("西", 25000),
                ("北", 15000),
            ],
        ),
        # ③ マイナス点数を含む
        (
            {"東": -5000, "南": 10000, "西": 45000, "北": 50000},
            [
                ("北", 50000),
                ("西", 45000),
                ("南", 10000),
                ("東", -5000),
            ],
        ),
        # ④ 点数の変動によって順位が逆転
        (
            {"東": 28000, "南": 20000, "西": 25000, "北": 27000},
            [
                ("東", 28000),
                ("北", 27000),
                ("西", 25000),
                ("南", 20000),
            ],
        ),
    ],
)
def test_get_ranking(scores, expected):
    result = get_ranking(scores)

    assert result == expected


